// appendFeedItem appends the item under id; once: unless the feed has that id already (fresh false).
func (s *Service) appendFeedItem(ctx context.Context, id string, once bool, conversation, kind, ref string, body any, at time.Time) (it FeedItem, fresh bool, err error) {
	if s.isLeaderRef(conversation) { // a task leader's agent is no conversation: nobody reads a feed there (task_leader.go)
		return FeedItem{}, true, nil
	}
	it = FeedItem{ID: id, Conversation: conversation, At: at.UTC(), Kind: kind, Ref: ref}
	if body != nil {
		raw, err := json.Marshal(body)
		if err != nil {
			return FeedItem{}, false, err
		}
		it.Body = raw
	}
	if st := s.store(); st == nil {
		s.tasks.mu.Lock()
		if kind == feedMessage && s.duplicateDismissedDraft(it) {
			s.tasks.mu.Unlock()
			return FeedItem{}, true, nil
		}
		if once && slices.ContainsFunc(s.tasks.feed[conversation], func(have FeedItem) bool { return have.ID == id }) {
			s.tasks.mu.Unlock()
			return FeedItem{}, false, nil
		}
		s.tasks.feed[conversation] = append(s.tasks.feed[conversation], it)
		s.tasks.mu.Unlock()
	} else {
		if once {
			if have, err := st.FeedItem(ctx, id); err != nil {
				return FeedItem{}, false, err
			} else if have != nil {
				return FeedItem{}, false, nil
			}
		}
		row := db.FeedRow{ID: it.ID, Conversation: conversation, At: it.At, Kind: kind, Ref: ref, Body: it.Body}
		if ds, ok := st.(draftFeedStore); kind == feedMessage && ok {
			inserted, err := ds.AppendDraftFeed(ctx, row)
			if err != nil || !inserted {
				return FeedItem{}, true, err
			}
		} else if err := st.AppendFeed(ctx, row); err != nil {
			if have, lookErr := st.FeedItem(ctx, id); once && lookErr == nil && have != nil {
				return FeedItem{}, false, nil // written meanwhile by another look at the same turn
			}
			return FeedItem{}, false, err
		}
	}
	s.event(ctx, map[string]any{"type": "assistant_feed", "conversation": conversation, "item": it})
	if kind == feedReceipt {
		s.interruptsSoon() // a task went on after being cut off (interruptions.go)
	}
	return it, true, nil
}

const feedPage = 500

// feedItems is a conversation's items after since, oldest first (with the message cards sent after since: the client
// has them, not that they went out), without the plans they name: for readers that look only at the items.
func (s *Service) feedItems(ctx context.Context, conversation string, since time.Time) ([]FeedItem, error) {
	items, err := s.rawFeed(ctx, conversation, since)
	if err != nil {
		return nil, err
	}
	for i, item := range items {
		items[i] = readTaskNotice(item)
	}
	s.settleCards(ctx, items)
	s.fileCards(ctx, items)
	return s.resolveInterruptions(ctx, conversation, items), nil
}

// rawFeed is feedItems as stored, with nothing worked out on reading.
func (s *Service) rawFeed(ctx context.Context, conversation string, since time.Time) ([]FeedItem, error) {
	var items []FeedItem
	if st := s.store(); st == nil {
		s.tasks.mu.Lock()
		for _, it := range s.tasks.feed[conversation] {
			at, changed := cardSentAt(it), cardChangedAt(it)
			if it.At.After(since) || it.Kind == feedMessage && (at != nil && at.After(since) || changed != nil && changed.After(since)) {
				items = append(items, it)
			}
		}
		s.tasks.mu.Unlock()
	} else {
		rows, err := st.Feed(ctx, conversation, since, feedPage)
		if err != nil {
			return nil, err
		}
		for _, r := range rows {
			items = append(items, FeedItem{ID: r.ID, Conversation: r.Conversation, At: r.At, Kind: r.Kind, Ref: r.Ref, Body: r.Body})
		}
	}
	return items, nil
}

// feed is feedItems and the plans they name.
func (s *Service) feed(ctx context.Context, conversation string, since time.Time) ([]FeedItem, map[string]*TaskPlan, error) {
	items, err := s.feedItems(ctx, conversation, since)
	if err != nil {
		return nil, nil, err
	}
	return items, s.feedPlans(ctx, items), nil
}

// feedPlans are the plans items' plan cards name, by id. A plan that is gone is left out, and so is every plan when
// reading them fails: the cards still show. The database reads them all in one query, not one per card.
func (s *Service) feedPlans(ctx context.Context, items []FeedItem) map[string]*TaskPlan {
	var ids []string
	seen := map[string]bool{}
	for _, it := range items {
		if it.Kind == feedPlan && !seen[it.Ref] {
			seen[it.Ref] = true
			ids = append(ids, it.Ref)
		}
	}
	plans := make(map[string]*TaskPlan, len(ids))
	st := s.store()
	if st == nil {
		for _, id := range ids {
			if p, err := s.loadPlan(ctx, id); err == nil {
				plans[id] = p
			}
		}
		return plans
	}
	if len(ids) == 0 {
		return plans
	}
	rows, err := st.TaskPlansByID(ctx, ids)
	if err != nil {
		s.logf("feed: read %d plans: %v", len(ids), err)
		return plans
	}
	for _, row := range rows {
		plans[row.ID] = planFromRow(row)
	}
	return plans
}

// planStartsAtOnce: every task only reads, was asked for by the user in this turn (while start_requested_tasks is on),
// or is a kind the user said to start without asking (its directory or one it is under, task_trust_scope.go).
func (s *Service) planStartsAtOnce(ctx context.Context, tasks []PlanTask) bool {
	return s.planAutoStartReasons(ctx, tasks, nil) != nil
}

// planAutoStartReasons gives each task's reason in plan order, or nil if the whole plan must wait. A scheduled
// round's grant is read only if a task needs it (schedule_grant.go).
func (s *Service) planAutoStartReasons(ctx context.Context, tasks []PlanTask, granted func() func(PlanTask) bool) []string {
	trusted := s.trustCover(ctx)
	requested := s.startRequestedTasks(ctx)
	reasons := make([]string, len(tasks))
	var cover func(PlanTask) bool
	for i, t := range tasks {
		switch {
		case t.Readonly:
			reasons[i] = "read-only"
		case requested && t.UserRequested:
			reasons[i] = "requested by the user this turn"
		case trustedTask(trusted, t):
			reasons[i] = "trusted directory or repository"
		default:
			if cover == nil && granted != nil {
				cover = granted()
				granted = nil
			}
			if cover == nil || !cover(t) {
				return nil
			}
			reasons[i] = "allowed by the user's schedule grant"
		}
	}
	return reasons
}

// trustKey names a kind of task the user can let start without asking: a machine's repository (Repo, every worktree
// of it) or, outside one or when the machine could not say, its exact directory; reading or editing (#8259).
func trustKey(t PlanTask) string {
	dir := t.Repo
	if dir == "" {
		dir = taskRunDir(t)
	}
	return t.Machine + "|" + dir + "|" + trustMode(t)
}

// trustFolderKey is the kind of t's exact directory: what every key was before #8259, and what trustKey is while the
// repository is unknown. The directory that runs, never the one a plan was made from when its workspace is another.
func trustFolderKey(t PlanTask) string {
	return t.Machine + "|" + taskRunDir(t) + "|" + trustMode(t)
}

// taskRunDir is the folder t runs in, as far as the hub knows yet: the workspace it resolved to on its machine (an
// existing workspace may be in another repository than Cwd), else Cwd. A new checkout not made yet is not a folder
// the machine can name a repository for: until admission makes it, the folder it is made from (Cwd) stands for it, and
// admission resolves again from the checkout made (admitTaskWorkspace).
func taskRunDir(t PlanTask) string {
	r := t.WorkspaceResolved
	if r == nil || r.Path == "" || r.Machine != t.Machine || !proto.NodeAbs(r.Path) {
		return t.Cwd
	}
	if !r.Created && t.Workspace != nil && t.Workspace.Mode == workspaceNew {
		return t.Cwd
	}
	return r.Path
}

func trustMode(t PlanTask) string {
	if t.Readonly {
		return "read"
	}
	return "edit"
}

// trustedTask: the user lets t's kind start without asking (covered: trustCover), by its repository or by its exact
// directory (a key remembered before #8259, or while the repository was unknown).
func trustedTask(covered func(key string) bool, t PlanTask) bool {
	return covered(trustKey(t)) || covered(trustFolderKey(t))
}

// repoLookup bounds asking a machine which repository a task's directory is in.
const repoLookup = 5 * time.Second

const (
	// taskDirCacheTTL bounds reuse of structural directory/repository metadata across placement, plan, start, and admission.
	taskDirCacheTTL        = 10 * time.Second
	taskDirCacheMaxEntries = 256
)

type taskCacheEntry[T any] struct {
	val T
	exp time.Time
}

type taskCacheFlight[T any] struct {
	done     chan struct{}
	waiters  int
	cancel   context.CancelFunc
	cacheKey string
	val      T
	err      error
}

// taskMetaCache coalesces concurrent identical node metadata RPCs and caches bounded positive answers for taskDirCacheTTL.
// Errors and uncacheable results are never stored. Canceling one waiter does not abort a flight shared with live peers,
// while canceling the final waiter aborts the underlying RPC promptly.
type taskMetaCache[T any] struct {
	mu       sync.Mutex
	entries  map[string]taskCacheEntry[T]
	inFlight map[string]*taskCacheFlight[T]
}

func (c *taskMetaCache[T]) putLocked(now time.Time, key string, val T, aliases func(T) []string) {
	c.putAtLocked(now, now.Add(taskDirCacheTTL), key, val, aliases)
}

func (c *taskMetaCache[T]) putAtLocked(now, exp time.Time, key string, val T, aliases func(T) []string) {
	if c.entries == nil {
		c.entries = map[string]taskCacheEntry[T]{}
	}
	keys := []string{key}
	if aliases != nil {
		for _, alias := range aliases(val) {
			if alias != "" && alias != key {
				keys = append(keys, alias)
			}
		}
	}
	if len(c.entries)+len(keys) > taskDirCacheMaxEntries {
		for k, e := range c.entries {
			if !now.Before(e.exp) {
				delete(c.entries, k)
			}
		}
		if len(c.entries)+len(keys) > taskDirCacheMaxEntries {
			clear(c.entries)
		}
	}
	for _, k := range keys {
		c.entries[k] = taskCacheEntry[T]{val: val, exp: exp}
	}
}

func (c *taskMetaCache[T]) getOrFetch(
	ctx context.Context,
	now func() time.Time,
	flightKey, cacheKey string,
	timeout time.Duration,
	cacheable func(T) bool,
	aliases func(T) []string,
	fetch func(context.Context) (T, error),
) (T, error) {
	var zero T
	if err := ctx.Err(); err != nil {
		return zero, err
	}
	ts := now()
	c.mu.Lock()
	if cacheKey != "" {
		if e, ok := c.entries[cacheKey]; ok {
			if ts.Before(e.exp) {
				c.mu.Unlock()
				return e.val, nil
			}
			delete(c.entries, cacheKey)
		}
	}
	f, joined := c.inFlight[flightKey]
	if joined {
		f.waiters++
		c.mu.Unlock()
	} else {
		callCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), timeout)
		f = &taskCacheFlight[T]{done: make(chan struct{}), waiters: 1, cancel: cancel, cacheKey: cacheKey}
		if c.inFlight == nil {
			c.inFlight = map[string]*taskCacheFlight[T]{}
		}
		c.inFlight[flightKey] = f
		c.mu.Unlock()
		go func() {
			defer cancel()
			val, err := fetch(callCtx)
			cancel()
			c.mu.Lock()
			f.val, f.err = val, err
			if err == nil && cacheKey != "" && (cacheable == nil || cacheable(val)) {
				c.putLocked(now(), cacheKey, val, aliases)
			}
			if c.inFlight[flightKey] == f {
				delete(c.inFlight, flightKey)
			}
			c.mu.Unlock()
			close(f.done)
		}()
	}

	select {
	case <-f.done:
		if f.err == nil && cacheKey != "" && cacheKey != f.cacheKey && (cacheable == nil || cacheable(f.val)) {
			c.mu.Lock()
			c.putLocked(now(), cacheKey, f.val, aliases)
			c.mu.Unlock()
		}
		return f.val, f.err
	case <-ctx.Done():
		c.mu.Lock()
		f.waiters--
		last := f.waiters == 0
		if last && c.inFlight[flightKey] == f {
			delete(c.inFlight, flightKey)
		}
		cancel := f.cancel
		c.mu.Unlock()
		if last {
			cancel()
		}
		return zero, ctx.Err()
	}
}

type taskDirRPCCache struct {
	now       func() time.Time // tests override to advance cache expiry deterministically
	dirExists taskMetaCache[bool]
	worktree  taskMetaCache[proto.WorktreeStatus]
	workspace taskMetaCache[proto.Workspace]
}

func (s *Service) taskMetaNow() time.Time {
	if s.tasks.dirMeta.now != nil {
		return s.tasks.dirMeta.now()
	}
	return time.Now()
}

func taskDirCacheKey(machine, dir string) string {
	if dir == "" {
		return machine + "\x00"
	}
	return machine + "\x00" + proto.NodeClean(dir)
}

func cacheableWorktreeStatus(st proto.WorktreeStatus) bool {
	if st.Path == "" {
		return true
	}
	if !proto.NodeAbs(st.Path) {
		return false
	}
	return !st.Worktree || st.Root == "" || proto.NodeAbs(st.Root)
}

// taskWorktreeStatus queries structural repository identity (Path, Worktree, Root) for dir on machine with short-TTL
// caching and in-flight singleflight deduplication. Mutable worktree fields (dirty, unmerged, branch) are never cached.
func (s *Service) taskWorktreeStatus(ctx context.Context, machine, dir string, timeout time.Duration) (proto.WorktreeStatus, error) {
	key := taskDirCacheKey(machine, dir)
	return s.tasks.dirMeta.worktree.getOrFetch(
		ctx,
		s.taskMetaNow,
		key,
		key,
		timeout,
		cacheableWorktreeStatus,
		func(st proto.WorktreeStatus) []string {
			if st.Path != "" && proto.NodeAbs(st.Path) {
				return []string{taskDirCacheKey(machine, st.Path)}
			}
			return nil
		},
		func(callCtx context.Context) (proto.WorktreeStatus, error) {
			var st proto.WorktreeStatus
			if err := s.call(callCtx, machine, "worktree.status", map[string]any{"cwd": dir}, &st); err != nil {
				return proto.WorktreeStatus{}, err
			}
			return proto.WorktreeStatus{
				Path:     st.Path,
				Worktree: st.Worktree,
				Root:     st.Root,
			}, nil
		},
	)
}

// aliasTaskWorktreeStatus records aliasDir under srcDir's existing cached worktree identity without extending its TTL.
func (s *Service) aliasTaskWorktreeStatus(machine, srcDir, aliasDir string) {
	if srcDir == "" || aliasDir == "" {
		return
	}
	srcKey, aliasKey := taskDirCacheKey(machine, srcDir), taskDirCacheKey(machine, aliasDir)
	if srcKey == aliasKey {
		return
	}
	now := s.taskMetaNow()
	s.tasks.dirMeta.worktree.mu.Lock()
	defer s.tasks.dirMeta.worktree.mu.Unlock()
	src, ok := s.tasks.dirMeta.worktree.entries[srcKey]
	if !ok || !now.Before(src.exp) {
		return
	}
	s.tasks.dirMeta.worktree.putAtLocked(now, src.exp, aliasKey, src.val, nil)
}

// resolveTaskRepo sets t.Repo from what t's machine says of the folder t runs in (taskRunDir; worktree.status, which
// nodes answer since #6115): the main checkout of the repository, for its main checkout and every linked worktree
// alike. Whatever it cannot learn (the machine offline, an older or failing node, a folder in no repository) leaves
// Repo "", so the kind stays that exact folder: never wider than before #8259, and never the repository of a folder
// the task does not run in.
func (s *Service) resolveTaskRepo(ctx context.Context, t *PlanTask) {
	dir := taskRunDir(*t)
	t.Repo, t.repoOf = "", t.Machine+"\x00"+proto.NodeClean(dir)
	if t.scratchWorkspace() {
		return
	}
	st := t.cwdStatus
	if st == nil || (!statusNames(*st, t.cwdStatusOf, t.repoOf) && (t.cwdStatusResolved == "" || t.cwdStatusResolved != t.repoOf)) {
		ctx, cancel := context.WithTimeout(ctx, repoLookup)
		defer cancel()
		got, err := s.taskWorktreeStatus(ctx, t.Machine, dir, repoLookup)
		if err != nil {
			s.logf("tasks: trust: repository of %s on %s: %v", dir, t.Machine, err)
			return
		}
		st = &got
	}
	t.Repo = repoOfStatus(*st)
}

// statusNames: a worktree.status answer asked for of (machine NUL folder) says what it says of want too: the same
// folder, or the top level of the checkout that folder is in (one checkout, one repository).
func statusNames(st proto.WorktreeStatus, of, want string) bool {
	if of == want {
		return true
	}
	machine, _, _ := strings.Cut(of, "\x00")
	return st.Path != "" && proto.NodeAbs(st.Path) && machine+"\x00"+proto.NodeClean(st.Path) == want
}

// repoOfStatus is the repository worktree.status names: the main checkout, which is Root for a linked worktree and
// the folder's own top level otherwise. "" when it names none.
func repoOfStatus(st proto.WorktreeStatus) string {
	dir := st.Path
	if st.Worktree {
		dir = st.Root
	}
	if dir == "" || !proto.NodeAbs(dir) {
		return ""
	}
	return proto.NodeClean(dir)
}

// trustedKinds is the kinds the user lets start without asking; none when they cannot be read, so that a plan asks.
// What writes tasks.trust reads it with trustedKindsErr instead.
func (s *Service) trustedKinds(ctx context.Context) map[string]bool {
	have, err := s.trustedKindsErr(ctx)
	if err != nil {
		s.logf("tasks: trust: read: %v", err)
		return map[string]bool{}
	}
	return have
}

// trustedKindsErr is trustedKinds with the read's error: a write built on a failed read would replace every kind
// remembered before.
func (s *Service) trustedKindsErr(ctx context.Context) (map[string]bool, error) {
	out := map[string]bool{}
	st := s.store()
	if st == nil {
		return out, nil
	}
	var keys []string
	ok, err := st.Setting(ctx, trustSetting, &keys)
	if err != nil {
		return nil, err
	}
	if ok {
		for _, k := range keys {
			out[k] = true
		}
	}
	return out, nil
}

// trustKinds remembers the kinds of tasks so that similar plans start without asking. When the kinds remembered
// before cannot be read it remembers nothing: the next similar plan asks again, and no kind is lost.
func (s *Service) trustKinds(ctx context.Context, tasks []PlanTask) {
	st := s.store()
	if st == nil {
		return
	}
	s.tasks.trustMu.Lock()
	defer s.tasks.trustMu.Unlock()
	have, err := s.trustedKindsErr(ctx)
	if err != nil {
		s.logf("tasks: trust: not remembering %d tasks' kinds: read: %v", len(tasks), err)
		return
	}
	for _, t := range tasks {
		have[trustKey(t)] = true
	}
	keys := make([]string, 0, len(have))
	for k := range have {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	if err := st.PutSetting(ctx, trustSetting, keys); err != nil {
		s.logf("tasks: trust: %v", err)
	}
}

