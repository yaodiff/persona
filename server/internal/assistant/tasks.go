func (s *Service) listTaskPlans(w http.ResponseWriter, r *http.Request) {
	ctx := r.Context()
	query := r.URL.Query()
	conv, scoped := query.Get("conversation"), query.Has("conversation")
	ext := r.Header.Get(RoleHeader) == roleExtension
	plans := []*TaskPlan{}
	if ext && !scoped {
		// Extensions can read individual conversation feeds. The main pending view spans conversations.
		apierr.WriteJSON(w, map[string]any{"plans": plans})
		return
	}
	if ext && s.feedHiddenFromExtension(ctx, conv) {
		apierr.Write(w, http.StatusNotFound, errNoSuchConversation)
		return
	}
	var pending []*TaskPlan
	var err error
	if scoped {
		pending, err = s.openTaskPlans(ctx)
		pending = slices.DeleteFunc(pending, func(p *TaskPlan) bool { return p.Conversation != conv })
	} else {
		pending, err = s.mainPendingPlans(ctx)
	}
	if err != nil {
		apierr.Write(w, http.StatusServiceUnavailable, err)
		return
	}
	var visible map[string]*TaskPlan
	if ext {
		byID := make(map[string]*TaskPlan, len(pending))
		for _, p := range pending {
			byID[p.ID] = p
		}
		_, visible, _ = s.extensionFeed(ctx, nil, byID)
	}
	lang := s.requestLang(r)
	for _, p := range pending {
		if !ext || visible[p.ID] != nil {
			plans = append(plans, s.planWithSpace(ctx, s.planWithSuggestion(ctx, p, lang)))
		}
	}
	apierr.WriteJSON(w, map[string]any{"plans": plans})
}

func (s *Service) taskRoutes() {
	s.draftDecisionRoutes()
	s.doneCheckRoute()
	s.taskTerminalRoute()
	s.handle("POST /api/v1/task-plans/{id}/workspace-preview", s.previewPlanWorkspaces)
	s.handle("GET /api/v1/task-plans", s.listTaskPlans)
	s.handle("GET /api/v1/task-plans/{id}", func(w http.ResponseWriter, r *http.Request) {
		p, err := s.loadPlan(r.Context(), r.PathValue("id"))
		if err != nil {
			planErr(w, err)
			return
		}
		apierr.WriteJSON(w, map[string]any{"plan": s.planWithSuggestion(r.Context(), p, s.requestLang(r))})
	})
	s.handle("POST /api/v1/task-plans/{id}/start", func(w http.ResponseWriter, r *http.Request) {
		if !fullRole(r) {
			apierr.Write(w, http.StatusForbidden, errors.New("read-only role cannot start tasks"))
			return
		}
		var in struct {
			Tasks    []PlanTask `json:"tasks"`
			Remember bool       `json:"remember"`
			// ScheduleGrant: let the scheduled task whose round made this plan start these kinds by itself (#8045).
			ScheduleGrant bool `json:"schedule_grant"`
		}
		if r.ContentLength != 0 {
			if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&in); err != nil {
				apierr.Write(w, http.StatusBadRequest, err)
				return
			}
		}
		ctx := ownerStart(r.Context())
		if in.ScheduleGrant {
			ctx = scheduleGranting(ctx)
		}
		p, err := s.startPlan(ctx, r.PathValue("id"), in.Tasks, in.Remember)
		if err != nil {
			planErr(w, err)
			return
		}
		apierr.WriteJSON(w, map[string]any{"plan": s.planWithSpace(r.Context(), p)})
	})
	s.handle("POST /api/v1/task-plans/{id}/dismiss", func(w http.ResponseWriter, r *http.Request) {
		if !fullRole(r) {
			apierr.Write(w, http.StatusForbidden, errors.New("read-only role cannot change tasks"))
			return
		}
		p, err := s.dismissPlan(r.Context(), r.PathValue("id"))
		// Don't Start on a card already started, dismissed or withdrawn elsewhere (another device, the conversation's
		// task_plan_withdraw) while no event reached this client: answer with the plan as it is, so the client's card
		// shows what happened instead of a 409 the user can only tap again (an iOS app held such a card until restarted).
		if errors.Is(err, errPlanNotOpen) {
			if cur, lerr := s.loadPlan(r.Context(), r.PathValue("id")); lerr == nil && cur.State != planOpen {
				p, err = cur, nil
			}
		}
		if err != nil {
			planErr(w, err)
			return
		}
		apierr.WriteJSON(w, map[string]any{"plan": s.planWithSpace(r.Context(), p)})
	})
	s.handle("POST /api/v1/todos/{id}/retry", func(w http.ResponseWriter, r *http.Request) {
		if !fullRole(r) {
			apierr.Write(w, http.StatusForbidden, errors.New("read-only role cannot start tasks"))
			return
		}
		// An optional body names another launcher of the same computer (and its model) to start with (#10365, hello
		// feature task_retry_launcher); none, or an empty one, retries as the plan has it.
		var in struct {
			Launcher string `json:"launcher"`
			Model    string `json:"model"`
		}
		if r.ContentLength != 0 {
			if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<16)).Decode(&in); err != nil && !errors.Is(err, io.EOF) {
				apierr.Write(w, http.StatusBadRequest, err)
				return
			}
		}
		t, err := s.retryTaskWith(r.Context(), r.PathValue("id"), retryWith{launcher: in.Launcher, model: in.Model, by: "user"})
		var refused retryRefused
		switch {
		case err == nil:
			apierr.WriteJSON(w, map[string]any{"todo": t})
		case errors.Is(err, db.ErrTodoNotFound):
			apierr.Write(w, http.StatusNotFound, err)
		case errors.Is(err, errTaskNotRetryable), errors.Is(err, errTaskNotInPlan), errors.Is(err, errMachineOffline), errors.As(err, &refused):
			apierr.Write(w, http.StatusConflict, err)
		default:
			planErr(w, err)
		}
	})
	s.handle("POST /api/v1/todos/{id}/start/answer", s.postTaskStartAnswer) // the startup question its start stopped on (start_answer.go)
	s.handle("GET /api/v1/assistant/conversations/{id}/feed", func(w http.ResponseWriter, r *http.Request) {
		var since time.Time
		if s := r.URL.Query().Get("since"); s != "" {
			t, err := time.Parse(time.RFC3339Nano, s)
			if err != nil {
				apierr.Write(w, http.StatusBadRequest, fmt.Errorf("since: %v", err))
				return
			}
			since = t
		}
		query := r.URL.Query()
		paginated := query.Get("paginate") == "1" || query.Has("cursor")
		if query.Has("cursor") && (query.Get("cursor") == "" || query.Has("since")) {
			apierr.Write(w, http.StatusBadRequest, errFeedCursor)
			return
		}
		ext := r.Header.Get(RoleHeader) == roleExtension
		if ext && s.feedHiddenFromExtension(r.Context(), r.PathValue("id")) { // feed_scope.go
			apierr.Write(w, http.StatusNotFound, errNoSuchConversation)
			return
		}
		var items []FeedItem
		var nextCursor string
		var err error
		if paginated {
			items, nextCursor, err = s.pagedFeed(r.Context(), r.PathValue("id"), since, query.Get("cursor"))
		} else {
			items, err = s.feedItems(r.Context(), r.PathValue("id"), since)
		}
		if err != nil {
			status := http.StatusServiceUnavailable
			if errors.Is(err, errFeedCursor) {
				status = http.StatusBadRequest
			}
			apierr.Write(w, status, err)
			return
		}
		plans := s.feedPlans(r.Context(), items)
		var pendingIDs []string
		// Main watches pending plans from every conversation of this manager. Extension
		// tokens retain their existing conversation-only feed and visibility rules.
		if !ext && r.PathValue("id") == s.settings(r.Context()).Main {
			pending, readErr := s.mainPendingPlans(r.Context())
			if readErr != nil {
				apierr.Write(w, http.StatusServiceUnavailable, readErr)
				return
			}
			pendingIDs = make([]string, 0, len(pending))
			for _, p := range pending {
				pendingIDs = append(pendingIDs, p.ID)
				plans[p.ID] = p
			}
		}

		var shown func(TaskCard) bool
		if ext {
			items, plans, shown = s.extensionFeed(r.Context(), items, plans)
		}
		if len(plans) > 0 {
			// Older plans can still carry the error of a to-do closed since.
			// Load the live to-dos before projecting those plans for clients.
			_ = s.ensureTodosLoaded(r.Context())
		}
		for id, p := range plans {
			plans[id] = s.planWithSpace(r.Context(), s.planWithSuggestion(r.Context(), p, s.requestLang(r)))
		}
		if items == nil {
			items = []FeedItem{}
		}
		views, err := s.conversationViews(r.Context(), r.PathValue("id"))
		if err != nil {
			apierr.Write(w, http.StatusServiceUnavailable, err)
			return
		}
		actions, err := s.conversationViewActions(r.Context(), r.PathValue("id"))
		if err != nil {
			apierr.Write(w, http.StatusServiceUnavailable, err)
			return
		}
		blocks, err := s.conversationViewBlockKeys(r.Context(), r.PathValue("id"))
		if err != nil {
			apierr.Write(w, http.StatusServiceUnavailable, err)
			return
		}
		cards, cardErr := s.taskCards(r.Context(), items, plans)
		if cardErr != nil {
			s.logf("feed: task card projection: %v", cardErr)
		}
		if shown != nil && cards != nil {
			cards = slices.DeleteFunc(cards, func(c TaskCard) bool { return !shown(c) })
		}
		out := map[string]any{"items": items, "plans": plans, "task_cards": cards, "views": views, "view_actions": actions, "view_blocks": blocks}
		if pendingIDs != nil {
			out["pending_plan_ids"] = pendingIDs
		}
		if paginated {
			out["next_cursor"] = nextCursor
		}
		s.writeConversationJSON(r.Context(), w, r.PathValue("id"), out)
	})
	s.handle("POST /api/v1/assistant/conversations/{id}/route", func(w http.ResponseWriter, r *http.Request) {
		if !fullRole(r) {
			writeTypedNothing(w, http.StatusForbidden, "", errors.New("read-only role cannot send"))
			return
		}
		var in struct {
			TodoID  string `json:"todo_id"`
			Text    string `json:"text"`
			AskedAt string `json:"asked_at"`
		}
		if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<20)).Decode(&in); err != nil {
			writeTypedNothing(w, http.StatusBadRequest, "", err)
			return
		}
		if strings.TrimSpace(in.Text) == "" || in.TodoID == "" {
			writeTypedNothing(w, http.StatusBadRequest, "", errors.New("todo_id and text are required"))
			return
		}
		var it FeedItem
		var err error
		if in.AskedAt != "" {
			it, err = s.routeDecisionAnswer(r.Context(), r.PathValue("id"), in.TodoID, in.AskedAt, in.Text)
		} else {
			it, err = s.routeToTask(r.Context(), r.PathValue("id"), in.TodoID, in.Text)
		}
		if err != nil { // 409 with delivered: send_in_doubt for words that may be with the Agent (todo_write_outcome.go)
			keys := routeInDoubtKeys
			if in.AskedAt != "" { // words that answer a decision, which may still show when they could not be recorded
				keys = answerInDoubtKeys
			}
			writeRouteError(w, err, keys)
			return
		}
		apierr.WriteJSON(w, map[string]any{"item": it})
	})
}
