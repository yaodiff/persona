#!/usr/bin/env python3
"""Generate the extension wire types of every language from schema/extension/ (#1849).

    python3 scripts/gen/extension_schema.py           write the generated files
    python3 scripts/gen/extension_schema.py --check   exit 1 when a generated file differs from the schema's

The schemas are the one truth of the extension manifest, the process protocol and views; this turns them into Go
(sdk/go/wire), TypeScript (sdk/ts/src/wire.ts and the web's copy), Swift (apple/Packages/PersonaWire) and Kotlin
(android/core/contracts). The hub wire schemas (schema/wire/) go through the same code into the files each one's x-out
names. Only the subset described in schema/extension/README.md is understood; anything else stops the generator rather
than being guessed at. Standard library only.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# The generator itself is the wiregen package next to this file, one module per language; this file is the command.
sys.path.insert(0, str(Path(__file__).resolve().parent))

from wiregen import model as _model  # noqa: E402
from wiregen.arkts import gen_arkts  # noqa: E402,F401
from wiregen.go import GO_HEADER, GO_PACKAGE_DOC, go_calls, gen_go, gofmt  # noqa: E402,F401
from wiregen.kotlin import KOTLIN_KEYWORDS, KOTLIN_PACKAGE, gen_kotlin, kt_ident  # noqa: E402,F401
from wiregen.model import (DEFAULT_HEADER, HEADER, SIDES, Call, Def, Field, SchemaError, TypeRef,  # noqa: E402,F401
                           flat, flat_fields, for_apps, is_scalar, reserved_keys, same_type, unknown_doc)
from wiregen.names import (INITIALISMS, camel, comment, go_field, lower_camel, named, plural,  # noqa: E402,F401
                           upper_snake)
from wiregen.rust import gen_rust  # noqa: E402,F401
from wiregen.swift import SWIFT_KEYWORDS, gen_swift, swift_ident  # noqa: E402,F401
from wiregen.ts import gen_ts, ts_calls  # noqa: E402,F401

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "schema" / "extension"
SCHEMA_FILES = ["manifest.schema.json", "protocol.schema.json", "view.schema.json", "messaging.schema.json",
                "connector.schema.json", "channel.schema.json", "kb.schema.json", "todos.schema.json", "leaders.schema.json", "models.schema.json", "assistant.schema.json", "assistant_data.schema.json", "machines.schema.json", "browser.schema.json", "storage.schema.json", "stream.schema.json", "transcription.schema.json", "repository.schema.json", "memory.schema.json", "offload.schema.json", "routine.schema.json"]

GO_OUT = ROOT / "sdk/go/wire/wire_gen.go"
# The TypeScript SDK's types, and the web app's copy. A schema file marked "x-side": "plugin" (what only the hub and
# an extension's program say to each other: the connector, channel and knowledge-base calls) goes to the SDKs only:
# the Go and TypeScript ones, not the web app's copy, Swift or Kotlin, which the apps never read it with.
TS_SDK_OUT = ROOT / "sdk/ts/src/wire.ts"
TS_OUTS = [TS_SDK_OUT, ROOT / "web/src/lib/extension-wire.ts"]
SWIFT_OUT = ROOT / "apple/Packages/PersonaWire/Sources/PersonaWire/ExtensionWire.swift"
KOTLIN_OUT = ROOT / "android/core/contracts/src/main/kotlin/persona/core/contracts/generated/ExtensionWire.kt"
# The schemas themselves, next to the Go types: go:embed cannot reach outside the module, and wire.Validate (what the
# hub and extensions' tests check views and handshakes with) reads them.
GO_SCHEMA_DIR = ROOT / "sdk/go/wire/schema"
# The hub wire types of the domains the shared fixtures pin (spec/fixtures): one schema file each, generated by the same
# code into the files its x-out names (ts, swift, go, kotlin). Their Swift and Kotlin types carry no prefix.
WIRE_DIR = ROOT / "schema" / "wire"


def load(schema_dir: Path | None = None, schema_files: list[str] | None = None) -> dict[str, Def]:
    """The definitions of the extension schemas (or of the files given): wiregen.model.load with this command's
    defaults, read when called so a test can point them elsewhere."""
    return _model.load(SCHEMA_DIR if schema_dir is None else schema_dir,
                       SCHEMA_FILES if schema_files is None else schema_files)


def load_calls(defs: dict[str, Def]) -> list[Call]:
    """The calls and events of the extension schema files' x-methods / x-events."""
    return _model.load_calls(defs, SCHEMA_DIR, SCHEMA_FILES)


# ---------------------------------------------------------------------------------------------------------------------


def outputs(defs: dict[str, Def]) -> dict[Path, str]:
    apps = for_apps(defs)
    # The calls are what a program and the hub say to each other: the SDKs' only.
    calls = load_calls(defs)
    ts, ts_apps = gen_ts(defs, calls), gen_ts(apps)
    # Apple stream reduction validates original JSON before projecting permissive legacy native models.
    # Keep validation constraints generated from the same schemas as the wire types.
    schema_docs = {f: json.loads((SCHEMA_DIR / f).read_text())
                   for f in ("stream.schema.json", "view.schema.json", "protocol.schema.json")}
    schema_json = json.dumps(schema_docs, ensure_ascii=True, separators=(",", ":"))
    swift_schemas = '\npublic nonisolated enum ExtensionWireSchemas {\n    public static let json = ###"' + schema_json + '"###\n}\n'
    out = {GO_OUT: gofmt(gen_go(defs, calls)), SWIFT_OUT: gen_swift(apps) + swift_schemas, KOTLIN_OUT: gen_kotlin(apps)}
    for p in TS_OUTS:
        out[p] = ts if p == TS_SDK_OUT else ts_apps
    for f in SCHEMA_FILES:
        out[GO_SCHEMA_DIR / f] = (SCHEMA_DIR / f).read_text()
    out.update(wire_outputs())
    return {p: (s.rstrip("\n") + "\n") for p, s in out.items()}


WIRE_TARGETS = ("ts", "swift", "go", "kotlin", "arkts", "rust")


def declared_package(out: Path, suffix: str, derived: str) -> str:
    """The package of a generated file: derived from its directory, and the one every hand-written file there names."""
    pattern = re.compile(r"^package\s+([\w.]+)", re.M)
    for other in sorted(out.parent.glob("*" + suffix)):
        if other == out or other.name.endswith("_test.go"):
            continue
        m = pattern.search(other.read_text())
        if m and m.group(1) != derived:
            raise SchemaError(f"{out.parent.name}/{out.name}: {other.name} is package {m.group(1)}, not {derived}")
    return derived


# The wire files whose x-id definitions every other wire schema may name in a property's x-id (#15397).
SHARED_WIRE = ("ids.schema.json",)


def shared_outputs(defs: dict[str, Def], target: str, out: Path):
    """Where the shared files' IDs that defs use come from in target, for a file written to out: TypeScript and
    ArkTS a relative module, Go an import path and package; Swift and Kotlin need the ID's file in the same module
    or package, and nothing to import."""
    files = sorted({d.external for d in defs.values() if d.external})
    found = {}
    for f in files:
        theirs = json.loads((WIRE_DIR / f).read_text()).get("x-out", {}).get(target)
        if not theirs:
            raise SchemaError(f"{out.name}: uses IDs of {f}, which generates no {target}")
        theirs = ROOT / theirs
        if target in ("ts", "arkts"):
            rel = os.path.relpath(theirs.with_suffix(""), out.parent)
            found[f] = rel if rel.startswith(".") else "./" + rel
        elif target == "go":
            module = re.search(r"^module\s+(\S+)", (ROOT / "server/go.mod").read_text(), re.M).group(1)
            found[f] = (module + "/" + theirs.parent.relative_to(ROOT / "server").as_posix(), theirs.parent.name)
        elif target in ("swift", "kotlin") and theirs.parent != out.parent:
            raise SchemaError(f"{out.name}: the {target} IDs of {f} are in {theirs.parent}, not beside it")
    return found


def wire_outputs() -> dict[Path, str]:
    """The hub wire types: each schema/wire/<domain>.schema.json into the files its x-out names (ts, swift, go,
    kotlin, arkts, rust). Go and Kotlin take the package of the directory they are written to. Each file's defect hook
    (closed enums with x-unknown "count") is named after the schema: todo-view → TodoViewWire."""
    out: dict[Path, str] = {}
    for path in sorted(WIRE_DIR.glob("*.schema.json")):
        doc = json.loads(path.read_text())
        targets = doc.get("x-out", {})
        if not set(targets) <= set(WIRE_TARGETS) or not targets:
            raise SchemaError(f"{path.name}: x-out names output files for {', '.join(WIRE_TARGETS)} only")
        # x-typed-except: targets generated as if the schema had none of the typed keywords, while that target's
        # callers still read strings and maps (todo-view's Go until #15068's files move, typed core plan P4b).
        except_ = doc.get("x-typed-except", [])
        if not isinstance(except_, list) or not set(except_) <= set(targets):
            raise SchemaError(f"{path.name}: x-typed-except lists targets of its x-out")
        shared = tuple(f for f in SHARED_WIRE if f != path.name)
        typed_defs = _model.load(WIRE_DIR, [path.name], shared=shared)
        open_defs = _model.load(WIRE_DIR, [path.name], shared=shared, typed=False) if except_ else typed_defs

        def defs_for(target: str) -> dict[str, Def]:
            return open_defs if target in except_ else typed_defs

        imports = {target: shared_outputs(defs_for(target), target, ROOT / targets[target]) for target in targets}
        about = f"{doc.get('title', path.name)}: {doc.get('description', '')}".rstrip()
        header = [f"// Generated by scripts/gen/extension_schema.py from schema/wire/{path.name}; do not edit.",
                  f"// {about}"]
        stem = path.name.removesuffix(".schema.json")
        defects = camel(stem) + "Wire"
        if "ts" in targets:
            out[ROOT / targets["ts"]] = gen_ts(defs_for("ts"), header=header, defects=defects, modules=imports["ts"])
        if "swift" in targets:
            out[ROOT / targets["swift"]] = gen_swift(defs_for("swift"), header=header, prefix="", defects=defects)
        if "go" in targets:
            # The package's own files are hand-written: no package doc here, and a registry of its own per schema.
            go = ROOT / targets["go"]
            package = declared_package(go, ".go", go.parent.name)
            out[go] = gofmt(gen_go(defs_for("go"), header=[f"// Code generated by scripts/gen/extension_schema.py from "
                                                 f"schema/wire/{path.name}. DO NOT EDIT.", f"// {about}"],
                                   package=package, package_doc="", registry=lower_camel(stem) + "Defs",
                                   defects=defects, packages=imports["go"]))
        if "kotlin" in targets:
            kt = ROOT / targets["kotlin"]
            parts = kt.relative_to(ROOT).parts
            if "kotlin" not in parts[:-1]:
                raise SchemaError(f"{path.name}: x-out kotlin is not under a kotlin source root")
            package = declared_package(kt, ".kt", ".".join(parts[parts.index("kotlin") + 1:-1]))
            out[kt] = gen_kotlin(defs_for("kotlin"), header=header, prefix="", package=package, defects=defects)
        if "arkts" in targets:
            # ArkTS accepts this schema's plain TypeScript subset: interfaces, string enums and their ordered values.
            out[ROOT / targets["arkts"]] = gen_arkts(defs_for("arkts"), header=header, defects=defects,
                                                     modules=imports["arkts"])
        if "rust" in targets:
            # serde types; the crate that includes the file depends on serde (derive) and serde_json.
            out[ROOT / targets["rust"]] = gen_rust(defs_for("rust"), header=header, defects=defects)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on a difference")
    args = ap.parse_args()
    try:
        files = outputs(load())
    except SchemaError as e:
        print(f"schema: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if not args.check:
        # sdk/ts/src/wire.ts is also in the bundle `personad extension new` writes extensions from.
        subprocess.run([sys.executable, str(ROOT / "scripts" / "gen" / "sdk_bundle.py")], check=True)
    if stale:
        print("generated files differ from their schemas (run python3 scripts/gen/extension_schema.py):", file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
